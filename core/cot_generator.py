# Phrases a generated naive (DPO "rejected") trace only contains when the model echoes its own generation
# instructions ("To construct a naive thinking trace: ...", "The expected answer concept states ...").
# Such a negative is trivially separable from the chosen trace and teaches the model nothing.
NAIVE_META_LEAK_RE = re.compile("|".join([
    r"\bnaive\s+(?:internal\s+)?(?:thinking|reasoning|chain[- ]of[- ]thought)(?:\s+trace)?\b",
    r"\bexpected\s+answer(?:\s+concept)?\b",
    r"\b(?:construct|write|produce|generate|create)\s+(?:a|an|the)\s+(?:naive|rambling|unoptimi[sz]ed|verbose|flawed)\b",
    r"\b(?:rambling|unoptimi[sz]ed|flawed)\s+(?:internal\s+)?(?:thinking|reasoning)\s+trace\b",
    r"\bClearCoT\b", r"\bAppendix\s+A\.\d", r"\binformal\s+reasoning\s+flaws\b", r"\bconversational\s+canopy\b",
    r"\b(?:circular|unsupported)\s+inferential\s+leap\b", r"\binternal\s+monologue\b",
    r"^\W*(?:naive\s+)?thinking\s+trace\b",
]), re.IGNORECASE | re.MULTILINE)


def naive_trace_leak(text: str) -> Optional[str]:
    """The leaked instruction phrase in a naive trace, or None if the trace reads as genuine reasoning."""
    m = NAIVE_META_LEAK_RE.search(text or "")
    return m.group(0) if m else None

_ABBREVIATIONS = ("et al.", "e.g.", "i.e.", "vs.", "cf.", "pp.", "p.", "vol.", "no.", "dr.", "prof.")
# only whole abbreviations: "step." / "piano." must not be read as "p." / "no."
_ABBR_RE = re.compile(r"(?<![A-Za-z])(?:" + "|".join(re.escape(a) for a in sorted(_ABBREVIATIONS, key=len, reverse=True))
                      + r")", re.IGNORECASE)
_ABBR_TOKEN_RE = re.compile(r"__ABBR(\d+)__")


def mask_abbreviations(text: str) -> Tuple[str, List[str]]:
    """Replace abbreviations with placeholders so a sentence splitter does not break at their period.
    Returns the masked text and the original spellings (case kept) for unmask_abbreviations."""
    originals: List[str] = []

    def _rep(m):
        originals.append(m.group(0))
        return f"__ABBR{len(originals) - 1}__"
    return _ABBR_RE.sub(_rep, text), originals


def unmask_abbreviations(text: str, originals: List[str]) -> str:
    return _ABBR_TOKEN_RE.sub(lambda m: originals[int(m.group(1))] if int(m.group(1)) < len(originals) else m.group(0), text)


def _clean_discourse_sentence(sent: str) -> str:
    """Strips leading discourse markers, line numbers, and citations from sentences."""
    s = sent.strip()
    s = re.sub(r'^\d+[\s\.\:\)\-]+\s*', '', s)
    s = re.sub(
        r'^(?:for\s+example,?\s*|in\s+particular,?\s*|specifically,?\s*|furthermore,?\s*|moreover,?\s*|however,?\s*|consequently,?\s*|therefore,?\s*|third,?\s*|second,?\s*|first,?\s*|finally,?\s*|yet,?\s*|again,?\s*|notably,?\s*|in\s+addition,?\s*|as\s+a\s+result,?\s*)',
        '',
        s,
        flags=re.IGNORECASE
    )
    s = re.sub(
        r'^(?:according\s+to\s+(?:the\s+)?(?:document|text|author|passage|article|excerpt|research|source\s+text),?\s*)',
        '',
        s,
        flags=re.IGNORECASE
    )
    s = re.sub(
        r'^(?:based\s+on\s+(?:the\s+)?(?:document|text|passage|excerpt|article),?\s*)',
        '',
        s,
        flags=re.IGNORECASE
    )
    s = re.sub(
        r'^(?:as\s+stated\s+in\s+(?:the\s+)?(?:document|text|passage),?\s*)',
        '',
        s,
        flags=re.IGNORECASE
    )
    s = re.sub(
        r'^(?:a\s+related\s+point\s+is\s+that|this\s+(?:might\s+)?suggest(?:s)?\s+that|it\s+(?:is\s+)?(?:important|worth\s+noting|clear)\s+that|meaning\s+that|which\s+means\s+that|suggesting\s+that|indicating\s+that)\s+',
        '',
        s,
        flags=re.IGNORECASE
    )
    s = s.strip()
    if s and s[0].islower():
        s = s[0].upper() + s[1:]
    return s


def _lower_first_if_not_proper(text: str) -> str:
    if not text:
        return ""
    words = text.split(maxsplit=1)
    first = words[0]
    rest = (" " + words[1]) if len(words) > 1 else ""
    proper_names = {
        "turing", "gödel", "godel", "abelard", "llull", "descartes", "copeland",
        "marder", "penrose", "lucas", "schwartz", "caltech", "unesco", "ai", "ctm"
    }
    if first.isupper() or first.lower() in proper_names:
        return text
    return first[0].lower() + first[1:] + rest


def _stem_word(word: str) -> str:
    """Lightweight rule-based suffix stripper for concept matching."""
    w = word.lower()
    for suff in ("ing", "ical", "ic", "ness", "tion", "sion", "ment", "able", "ible", "ive", "ed", "es", "s", "ly"):
        if w.endswith(suff) and len(w) - len(suff) >= 3:
            return w[:-len(suff)]
    return w


def _matches_concept(concept: str, text: str) -> bool:
    """Checks whether a conceptual node/atom appears in text with lemmatization tolerance."""
    raw = concept.strip().lower()
    if not raw:
        return True
    text_lower = text.lower()
    if raw in text_lower:
        return True
    words = [re.sub(r'[^a-z0-9]', '', w) for w in raw.split()]
    stopwords = {"the", "and", "for", "with", "that", "this", "from", "are", "is", "was", "were", "been", "have", "has", "had", "to", "in", "on", "at", "by", "an", "a", "of"}
    words = [w for w in words if len(w) > 2 and w not in stopwords]
    if not words:
        return True
    text_words = set(re.findall(r'\b[a-z0-9]+\b', text_lower))
    text_stems = {_stem_word(w) for w in text_words}
    matched = sum(1 for w in words if w in text_words or _stem_word(w) in text_stems)
    ratio = matched / len(words)
    if len(words) <= 2:
        return ratio >= 1.0
    return ratio >= 0.75


def make_reasoning_direct(text: str) -> str:
    """
    Purge formal scaffolding, canned preambles, and meta-openings from ClearCoT reasoning traces,
    making the internal thought flow direct, active, and immediate (Occam razor).
    """
    if not text:
        return ""
    t = text.strip()

    # 1. Strip prompt echoes / question requirement intros
    t = re.sub(
        r'^(?:The\s+question\s+requires\s+(?:explaining|synthesizing|analyzing|evaluating|reconciling|addressing)\s+.*?(?<!\b[A-Za-z]\.)(?<!\b[A-Za-z])[.!?]\s*)',
        '',
        t,
        flags=re.IGNORECASE,
    )
    t = re.sub(r'^(?:The\s+question\s+requires\s+[^\.]*\.\s*)', '', t, flags=re.IGNORECASE)
    t = re.sub(r'^(?:The\s+inquiry\s+centers\s+on\s+whether\s+)', 'Whether ', t, flags=re.IGNORECASE)
    t = re.sub(r'^(?:The\s+dispute\s+hinges\s+on\s+whether\s+)', 'Whether ', t, flags=re.IGNORECASE)
    t = re.sub(r'^(?:The\s+problem\s+centers\s+on\s+reconciling\s+)', 'Reconciling ', t, flags=re.IGNORECASE)

    # 2. Strip meta-commentary sentences
    t = re.sub(r'(?:\.|\A)\s*The reasoning avoids meta-commentary[^\.]*\.?', '.', t, flags=re.IGNORECASE)
    t = re.sub(r'(?:\.|\A)\s*The conclusion follows necessarily from these premises\.?', '.', t, flags=re.IGNORECASE)
    t = re.sub(r'(?:\.|\A)\s*This avoids alternative interpretations where[^\.]*\.?', '.', t, flags=re.IGNORECASE)

    # 3. Tensions / conflicts transforms
    # "The core tension lies in Doerig et al.'s claim that..." -> "Doerig et al. argue that..."
    t = re.sub(
        r'^The\s+(?:core\s+|central\s+)?tension\s+(?:lies\s+in|involves)\s+([A-Z][a-zA-Z\s\.\'\-]+?)(?:[’\']s)?\s+claim\s+that\s+',
        r'\1 argues that ',
        t,
    )
    # "The core tension lies in reconciling X with Y." -> "Reconciling X with Y requires distinguishing their explanatory scopes."
    t = re.sub(
        r'^The\s+(?:core\s+|central\s+)?tension\s+(?:is|lies\s+in|involves)\s+reconciling\s+(.*?)\s+with\s+(.*?)\.\s+(?=(?:Premise|\b[A-Z]))',
        r'Reconciling \1 with \2 requires distinguishing their explanatory scopes. ',
        t,
        flags=re.IGNORECASE,
    )
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:is|lies\s+in|involves)\s+reconciling\s+', 'Reconciling ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:is|lies\s+in|involves)\s+distinguishing\s+between\s+', 'Distinguishing between ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:is|lies\s+in|involves)\s+distinguishing\s+', 'Distinguishing ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:lies\s+in|involves|arises\s+from)\s+(?:establishing|determining|evaluating)\s+', 'Evaluating ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+addresses\s+whether\s+', 'Evaluating whether ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+lies\s+in\s+whether\s+', 'Evaluating whether ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:lies\s+between|arises\s+between)\s+', 'A critical tension exists between ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+arises\s+from\s+(?:the\s+)?(?:identification|claim)\s+that\s+', 'The claim that ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+arises\s+from\s+', 'Addressing ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+(?:core\s+|central\s+)?tension\s+(?:lies\s+in|involves)\s+', '', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+tension\s+centers\s+on\s+reconciling\s+', 'Reconciling ', t, flags=re.IGNORECASE)
    t = re.sub(r'^The\s+tension\s+arises\s+between\s+', 'A critical tension exists between ', t, flags=re.IGNORECASE)

    # 4. Scaffolding & premise intros
    t = re.sub(r'\b(?:The\s+)?foundational\s+premises?\s+anchor\s+([A-Za-z0-9_\-\s]+?)\s+as\s+', r'\1 are modeled as ', t, flags=re.IGNORECASE)
    t = re.sub(r'\b(?:The\s+)?foundational\s+premises?\s+(?:establish(?:es)?|asserts?|posits?|anchors?|are|is)\s*(?:that|:)?\s*', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bPremises?\s+(?:establish(?:es)?|asserts?|posits?|are|is)\s*(?:that|:)?\s*', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bPremise\s+\d+\s*:\s*', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bPremise\s+\d+\s+(?:establish(?:es)?|asserts?|posits?)\s*(?:that)?\s*', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bThe\s+relational\s+chain\s+posits\s+that\s+', '', t, flags=re.IGNORECASE)
    # scaffolding only: drop it (the rewrite used to insert a fixed, document-specific claim here)
    t = re.sub(r'\bThis\s+conclusion\s+follows\s+from\s+the\s+foundational\s+premises\s+that\s+', '', t, flags=re.IGNORECASE)

    # 5. Bridges
    t = re.sub(r'\bThe\s+(?:critical\s+)?infer(?:ential|ence)\s+bridge\s+relies\s+on\s+the\s+contradiction\s*:\s*', 'Applying non-contradiction, ', t, flags=re.IGNORECASE)
    t = re.sub(r'\bThe\s+(?:critical\s+)?infer(?:ential|ence)\s+bridge\s+relies\s+on\s+', 'Applying ', t, flags=re.IGNORECASE)
    t = re.sub(r'\bThe\s+inferential\s+bridge\s+applies\s*:\s*', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bBy\s+applying\s+deductive\s+reasoning,?\s*(?:we\s+conclude\s+that\s+)?', '', t, flags=re.IGNORECASE)
    t = re.sub(r'\bThe\s+deduction\s+proceeds\s+by\s+recognizing\s+that\s+', 'Recognizing that ', t, flags=re.IGNORECASE)

    # 6. Citation format cleanup ("Doerig et al." -> "Doerig")
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\.?[’\']s\b', r"\1's", t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\.\s*', r'\1 ', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\b', r'\1', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+argue\b', r'\1 argues', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+assert\b', r'\1 asserts', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+posit\b', r'\1 posits', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+require\b', r'\1 requires', t)
    t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+interpret\b', r'\1 interprets', t)

    # 7. Clean punctuation & whitespace
    t = re.sub(r'\s*\.\s*\.', '.', t)
    t = re.sub(r';\s*', '; ', t)
    t = re.sub(r'\s*,\s*', ', ', t)
    t = re.sub(r'\s+', ' ', t).strip()

    # Protect abbreviations from sentence splitting
    t, _abbr_orig = mask_abbreviations(t)

    sents = re.split(r'(?<=[.!?])\s+', t)
    cleaned_sents = []
    for s in sents:
        s = s.strip()
        if not s:
            continue
        # Restore abbreviations
        s = unmask_abbreviations(s, _abbr_orig)
        if s.startswith('Reconciling ') and not any(v in s for v in [' requires', ' necessitates', ' demands', ' highlights', ' depends', ' hinges', ' involves', ' leads']):
            s = re.sub(r'\.$', ' requires distinguishing their respective operational roles.', s)
        if s.startswith('Distinguishing ') and not any(v in s for v in [' requires', ' necessitates', ' demands', ' highlights', ' depends', ' hinges', ' involves', ' leads', ' stems', ' centers']):
            s = re.sub(r'\.$', ' requires evaluating their differing cognitive foundations.', s)
        if s[0].islower():
            s = s[0].upper() + s[1:]
        cleaned_sents.append(s)

    res = ' '.join(cleaned_sents).strip()
    # Restore any remaining abbreviations
    res = unmask_abbreviations(res, _abbr_orig)
    if res and res[0].islower():
        res = res[0].upper() + res[1:]
    return res


