class CoTGenerator:
    # "prompted": the model writes <reasoning> as plain text with thinking off (the chat-template default).
    # "native":   the model's own thinking channel (enable_thinking) carries the trace, under the same
    #             constraints; only the SFT/chosen trace uses it. The DPO rejected trace stays prompted (it must
    #             ramble, which ClearCoT-trained thinking does not), and so does the token-savings baseline.
    REASONING_MODES = ("prompted", "native")

    def __init__(self, llm_client: Optional[LocalLLMClient] = None, reasoning_mode: str = "prompted"):
        self.llm_client = llm_client
        if reasoning_mode not in self.REASONING_MODES:
            raise ValueError(f"reasoning_mode must be one of {self.REASONING_MODES}")
        self.reasoning_mode = reasoning_mode

    @staticmethod
    def _native_prompt(prompt: str) -> str:
        """The prompted-mode instructions rewritten for the thinking channel: constraints apply to the thinking."""
        p = prompt.replace("1. <reasoning> MUST be", "1. Your thinking MUST be")
        p = p.replace("in <reasoning>", "in your thinking").replace("start <reasoning>", "start your thinking")
        p = re.sub(r"Output ONLY the tags:.*$",
                   "Do the deduction in your thinking. After thinking, output ONLY <answer>...</answer>:", p)
        return p

    def _format_conceptual_guide(
        self,
        logic_tree_text: str,
        target_claim: str,
        relevance_info: Optional[Dict[str, Any]] = None,
        curry_howard_term: Optional[str] = None,
    ) -> str:
        """Extract a natural conceptual guide from the nanoGentzen logic tree without turnstiles or LaTeX."""
        guidance = []
        for line in logic_tree_text.splitlines():
            if "Established:" in line:
                rule_match = re.search(r'\[(.*?)\]', line)
                rule_name = rule_match.group(1) if rule_match else "Deduction"
                item = line.split("Established:")[-1].strip(" `")
                # If sequent with turnstile, extract the goal after turnstile
                if "⊢" in item or "\\vdash" in item:
                    parts = re.split(r'\\?vdash', item)
                    subgoal = parts[-1].strip(" `")
                else:
                    subgoal = item

                subgoal = re.sub(r'->|\\to|→', ' leads to ', subgoal)
                subgoal = re.sub(r'[_]+', ' ', subgoal)
                subgoal = re.sub(r'[\[\]\{\}\$\(\)]', '', subgoal).strip()
                subgoal = re.sub(r'\s{2,}', ' ', subgoal)

                if subgoal and subgoal not in [g.split(": ", 1)[-1] for g in guidance]:
                    if "Axiom" in rule_name or "Premise" in rule_name:
                        guidance.append(f"- Active Fact: {subgoal}")
                    elif "Modus Ponens" in rule_name or "Imp_L" in rule_name:
                        guidance.append(f"- Inferential Step: {subgoal}")
                    else:
                        guidance.append(f"- Deductive Constraint: {subgoal}")

        if relevance_info:
            witnesses = relevance_info.get("relevant_witnesses", [])
            unused = relevance_info.get("unused_premises", [])
            if witnesses:
                clean_w = [re.sub(r'[_]+', ' ', w).strip() for w in witnesses if w]
                guidance.insert(0, f"- Load-Bearing Causal Premises: {', '.join(clean_w[:5])}")
            if unused:
                clean_u = [re.sub(r'[_]+', ' ', u).strip() for u in unused if u]
                guidance.append(f"- Non-Causal Distractors (OMIT from deduction): {', '.join(clean_u[:5])}")

        if target_claim:
            guidance.append(f"- Target Conclusion: {target_claim}")
        return "\n".join(guidance) if guidance else f"- Target Conclusion: {target_claim}"

    def build_cot_from_logic_tree(
        self,
        question: str,
        target_claim: str,
        logic_tree_text: str,
        context_text: str,
        model: str = "qwen2.5:7b",
        temperature: float = 0.25,
        max_tokens: int = 384,
        relevance_info: Optional[Dict[str, Any]] = None,
        curry_howard_term: Optional[str] = None,
        path_nodes: Optional[List[str]] = None,
        key_premises: Optional[List[str]] = None,
        is_verified: bool = True,
        epistemic_status: str = "PROVEN_TRUE",
    ) -> Dict[str, Any]:
        """
        Calls the user-selected LLM to build the CoT conditioned on the conceptual logical sequence.
        Defaults to 384 max_tokens (ideal for dense 120-250 token ClearCoT traces without blowing context windows).
        """
        if not self.llm_client or not self.llm_client.health_check():
            logger.warning("LLM client offline or unavailable; generating contextual structured CoT.")
            return self._heuristic_fallback(
                question,
                target_claim,
                logic_tree_text,
                context_text,
                error="LLM backend offline",
                path_nodes=path_nodes,
                key_premises=key_premises,
                is_verified=is_verified,
                epistemic_status=epistemic_status,
                relevance_info=relevance_info,
            )

        conceptual_guide = self._format_conceptual_guide(
            logic_tree_text,
            target_claim,
            relevance_info=relevance_info,
            curry_howard_term=curry_howard_term,
        )

        # Truncate context_text to ~1500 chars if excessively large to protect strict 2048-context engines
        safe_context = context_text.strip()
        if len(safe_context) > 2500:
            safe_context = safe_context[:2500].rsplit(".", 1)[0] + "."

        prompt = (
            f"### Grounded Domain Knowledge & Facts:\n{safe_context}\n\n"
            f"### Question (Q):\n{question}\n\n"
            f"### Target Proposition to Deduce (A):\n{target_claim}\n\n"
            f"### Grounded Deductive Logic Sequence (R):\n{conceptual_guide}\n\n"
            "Apply the authentic ClearCoT (Occam) methodology:\n"
            "1. <reasoning> MUST be a compact, load-bearing deductive proof trace (60-120 words), NOT a conversational essay or formal meta-analysis.\n"
            "   - Dive DIRECTLY into the active domain mechanisms and facts from the first word.\n"
            "   - NO canned intros like 'Foundational premises establish that...', 'The tension arises between...', 'The core tension lies in...', or 'Premise 1 establishes...'.\n"
            "   - Apply the deductive inference bridge showing why contrary readings or distractor hypotheses fail.\n"
            "   - Derive the necessary conclusion matching the Target Proposition.\n"
            "2. <answer> MUST be an authoritative, comprehensive direct answer (1-3 rich sentences) synthesizing the outcome without meta-discourse.\n"
            "CRITICAL NEGATIVE CONSTRAINTS:\n"
            "- NEVER use canned meta-openings like 'Foundational premises establish that...', 'The tension arises between...', 'The core tension lies in...', 'The inquiry centers on...', or 'The question requires...'.\n"
            "- NEVER mention 'nanoGentzen', 'the sequent', 'proof tree', 'Modus Ponens', or internal pipeline terms in <reasoning> or <answer>.\n"
            "- Do NOT write an essay or narrative background in <reasoning> (keep it purely deductive and focused on inferential mechanics).\n"
            "- Do NOT use robotic numbers or checklists (NEVER write '(1), (2)' or 'First, Second, Finally').\n"
            "- Do NOT refer to 'the text', 'the document', or 'according to the text' (reason directly about the real-world concepts).\n"
            "- Do NOT quote the guide labels (NEVER write 'The logical bridge connects...', 'To resolve this, we must first establish...', or 'Establish foundational concepts').\n"
            "- Do NOT start <reasoning> by stating the final answer; deduce it step-by-step.\n"
            "Output ONLY the tags: start immediately with <reasoning> and conclude with </answer>:"
        )

        native = self.reasoning_mode == "native"
        try:
            raw = self.llm_client.generate(
                prompt=self._native_prompt(prompt) if native else prompt,
                system_prompt=COT_BUILDER_SYSTEM_PROMPT,
                model=model,
                temperature=temperature,
                max_tokens=max(max_tokens, 768) if native else max_tokens,   # thinking + answer
                **({"chat_template_kwargs": {"enable_thinking": True}} if native else {}),
            )
            parsed = self._extract_qra(raw, fallback_question=question, fallback_answer=target_claim)
            if parsed and native:
                # Occam still writes a <reasoning> block after thinking (its trained format) and the parser prefers
                # <reasoning>; in native mode the trace is the thinking channel itself
                th = re.search(r"<think>(.*?)</think>", raw or "", re.DOTALL | re.IGNORECASE)
                if th and len(th.group(1).split()) > 10:
                    parsed["post_think_reasoning"] = parsed.get("reasoning", "")
                    parsed["reasoning"] = th.group(1).strip()
                else:
                    parsed["native_think_missing"] = True
            if parsed:
                parsed["reasoning_mode"] = self.reasoning_mode
                parsed["reasoning"] = self._sanitize_regular_text(parsed["reasoning"])
                parsed["answer"] = self._sanitize_regular_text(parsed["answer"])
                r_words = len(parsed["reasoning"].split())
                parsed["reasoning_tokens_estimate"] = int(r_words * 1.3)
                parsed["clarity_score"] = self._compute_clarity_score(parsed["reasoning"])
                parsed["is_fallback"] = False

                grounding = self.verify_cot_grounding(
                    reasoning=parsed["reasoning"],
                    answer=parsed["answer"],
                    logic_tree_res={
                        "is_verified": is_verified,
                        "logic_tree_text": logic_tree_text,
                        "relevance": relevance_info,
                        "epistemic_status": epistemic_status,
                    },
                    path_nodes=path_nodes,
                    key_premises=key_premises,
                    target_claim=target_claim,
                )
                parsed["grounding"] = grounding
                parsed["grounding_score"] = grounding["grounding_score"]
                parsed["is_grounded"] = grounding["is_grounded"]
                return parsed
            else:
                logger.warning(f"Failed to parse QRA from model output (length {len(raw)}). Using contextual fallback.")
                return self._heuristic_fallback(
                    question,
                    target_claim,
                    logic_tree_text,
                    context_text,
                    error="Failed to parse QRA tags from output",
                    path_nodes=path_nodes,
                    key_premises=key_premises,
                    is_verified=is_verified,
                    epistemic_status=epistemic_status,
                    relevance_info=relevance_info,
                )
        except Exception as e:
            logger.warning(f"CoT generation failed on model {model}: {e}. Generating contextual fallback.")
            return self._heuristic_fallback(
                question,
                target_claim,
                logic_tree_text,
                context_text,
                error=str(e),
                path_nodes=path_nodes,
                key_premises=key_premises,
                is_verified=is_verified,
                epistemic_status=epistemic_status,
                relevance_info=relevance_info,
            )

    def _extract_qra(
        self,
        text: str,
        fallback_question: str = "",
        fallback_answer: str = ""
    ) -> Optional[Dict[str, str]]:
        """
        Robust parser extracting question, reasoning (<reasoning>, <think>, <thought>, markdown),
        and answer from LLM output, preventing meta-scratchpads from polluting the extracted fields.
        """
        if not text or not text.strip():
            return None

        # 1. Question: from <question> tag if present, else default to fallback_question
        q_match = re.search(r'<question>(.*?)</question>', text, re.DOTALL | re.IGNORECASE)
        question = q_match.group(1).strip() if q_match else fallback_question

        reasoning = ""
        answer = ""
        # Strategy A: Check for explicit scratchpad resolution or revision markers
        # Matches: *Reasoning Revision:*, *Revised Reasoning:*, *Final Reasoning:*, *My Reasoning:*, *Reasoning:*
        rev_r_pattern = r'\*(?:My\s+|Final\s+|Revised\s+)?Reasoning(?:\s+Revision)?:\*\s*(.*?)(?=\*(?:My\s+|Final\s+|Revised\s+)?Answer(?:\s+Revision)?:\*|$)'
        rev_a_pattern = r'\*(?:My\s+|Final\s+|Revised\s+)?Answer(?:\s+Revision)?:\*\s*(.*?)(?=(?:\n\s*\n\s*Reasoning Tokens|\n\s*\n\s*nanoGentzen|\n\s*\n\s*Grounded Source|$))'

        rev_r_matches = list(re.finditer(rev_r_pattern, text, re.DOTALL | re.IGNORECASE))
        rev_a_matches = list(re.finditer(rev_a_pattern, text, re.DOTALL | re.IGNORECASE))

        if rev_r_matches:
            r_cand = rev_r_matches[-1].group(1).strip()
            r_cand = re.sub(r'(?:\d+\.\s*\*\*Review|\*\*Review\s+against|\*+Review\b).*$', '', r_cand, flags=re.IGNORECASE | re.DOTALL).strip()
            r_cand = re.sub(r'\*+(?:looks good|looks solid|checked|done|verified)\.?\*+', '', r_cand, flags=re.IGNORECASE).strip()
            r_cand = re.sub(r'\*+(?:Answer Check|Reasoning Check|Critique|Drafting)[^*]*\*+.*$', '', r_cand, flags=re.IGNORECASE | re.DOTALL).strip()
            r_cand = re.sub(r'</?(?:think|thought|answer|reasoning)>', '', r_cand, flags=re.IGNORECASE).strip()
            if len(r_cand.split()) > 10:
                reasoning = r_cand

        if rev_a_matches:
            a_cand = rev_a_matches[-1].group(1).strip()
            a_cand = re.sub(r'(?:\d+\.\s*\*\*Review|\*\*Review\s+against|\*+Review\b).*$', '', a_cand, flags=re.IGNORECASE | re.DOTALL).strip()
            a_cand = re.sub(r'\*+(?:looks good|looks solid|checked|done|verified)[^*]*\*+', '', a_cand, flags=re.IGNORECASE).strip()
            a_cand = re.sub(r'</?(?:think|thought|answer|reasoning)>', '', a_cand, flags=re.IGNORECASE).strip()
            if len(a_cand.split()) >= 3:
                answer = a_cand

        # Strategy B: Check properly paired <reasoning>...</reasoning> and <answer>...</answer>
        if not reasoning or not answer:
            r_blocks = re.findall(r'<reasoning>(.*?)</reasoning>', text, re.DOTALL | re.IGNORECASE)
            valid_r = [b.strip() for b in r_blocks if len(b.strip().split()) > 10 and not b.strip().startswith("`")]
            if valid_r and not reasoning:
                reasoning = valid_r[-1]

            a_blocks = re.findall(r'<answer>(.*?)</answer>', text, re.DOTALL | re.IGNORECASE)
            valid_a = [b.strip() for b in a_blocks if len(b.strip().split()) >= 3 and not b.strip().startswith("`")]
            if valid_a and not answer:
                answer = valid_a[-1]

        # Strategy C: Check <think>...</think>
        if not reasoning:
            think_blocks = re.findall(r'<think>(.*?)</think>', text, re.DOTALL | re.IGNORECASE)
            valid_th = []
            for b in think_blocks:
                cand = b.strip()
                # If block is an unexecuted planning scratchpad, check for inner resolution
                if any(bad in cand.lower() for bad in ("thinking process:", "1. **analyze", "**task:**", "**constraints:**", "*critical issue:*", "output only the tags:")):
                    inner_r = re.search(r'\*(?:My\s+|Final\s+|Revised\s+)?Reasoning(?:\s+Revision)?:\*\s*(.*?)(?=\*(?:My\s+|Final\s+|Revised\s+)?Answer(?:\s+Revision)?:\*|$)', cand, re.DOTALL | re.IGNORECASE)
                    if inner_r and len(inner_r.group(1).strip().split()) > 10:
                        valid_th.append(inner_r.group(1).strip())
                    continue
                if len(cand.split()) > 10 and not cand.startswith("`"):
                    valid_th.append(cand)
            if valid_th:
                reasoning = valid_th[-1]

        # Strategy D: Unclosed tags ONLY if substantive (>6 words) and not a meta-mention
        if not reasoning:
            r_unclosed = re.search(r'(?<![\(\*`])<reasoning>(?![\`\)\*])(.*?)$', text, re.DOTALL | re.IGNORECASE)
            if r_unclosed:
                cand = r_unclosed.group(1).strip()
                if "<answer>" in cand:
                    parts = re.split(r'(?<![\(\*`])<answer>(?![\`\)\*])', cand, flags=re.IGNORECASE)
                    cand_r = parts[0].strip()
                    if len(cand_r.split()) >= 6 and not cand_r.startswith(("):", "*Goal:*", "1.", "2.", "3.", "4.")):
                        reasoning = cand_r
                    if not answer and len(parts) > 1 and len(parts[1].strip().split()) >= 3:
                        cand_a = re.sub(r'</answer>', '', parts[1], flags=re.IGNORECASE).strip()
                        if not cand_a.startswith(("):", "*Goal:*", "1.", "2.", "3.", "4.")):
                            answer = cand_a

        # Strategy E: Markdown headers
        if not reasoning:
            sec_match = re.search(
                r'(?:#+\s*Reasoning|\*\*Reasoning:?\*\*|Reasoning:)\s*(.*?)(?=(?:#+\s*Answer|\*\*Answer:?\*\*|Answer:|$))',
                text,
                re.DOTALL | re.IGNORECASE
            )
            if sec_match and len(sec_match.group(1).strip().split()) > 10:
                reasoning = sec_match.group(1).strip()

        if not answer:
            ans_match = re.search(
                r'(?:#+\s*Answer|\*\*Answer:?\*\*|Answer:|Conclusion:)\s*(.*)',
                text,
                re.DOTALL | re.IGNORECASE
            )
            if ans_match and len(ans_match.group(1).strip().split()) >= 3:
                answer = ans_match.group(1).strip()

        # Strategy F: If no tags at all, split paragraphs
        if not reasoning and not answer:
            cleaned = text.strip()
            paragraphs = [p.strip() for p in cleaned.split("\n\n") if p.strip()]
            if len(paragraphs) >= 2:
                reasoning = "\n\n".join(paragraphs[:-1])
                answer = paragraphs[-1]
            elif len(cleaned) > 20:
                reasoning = cleaned
                answer = fallback_answer or "Established as derived."

        # Sanitize reasoning if it captured planning scratchpad text or review
        if reasoning and ("*Reasoning Revision:*" in reasoning or "5. **Review" in reasoning or "**Drafting Reasoning" in reasoning):
            sub_r = re.search(r'\*(?:My\s+|Final\s+|Revised\s+)?Reasoning(?:\s+Revision)?:\*\s*(.*?)(?=\*(?:My\s+|Final\s+|Revised\s+)?Answer(?:\s+Revision)?:\*|$)', reasoning, re.DOTALL | re.IGNORECASE)
            if sub_r and len(sub_r.group(1).strip().split()) > 10:
                reasoning = sub_r.group(1).strip()

        # Sanitize answer if it captured planning scratchpad text
        if answer and ("**Constraints:**" in answer or "**Analyze the Document Context:**" in answer or "Drafting the Answer" in answer or "**Review" in answer or "*Answer Revision:*" in answer or "Review against Constraints" in answer):
            sub_ans = re.search(r'\*(?:My\s+|Final\s+|Revised\s+)?Answer(?:\s+Revision)?:\*\s*(.*?)(?=(?:\n\s*\n\s*Reasoning Tokens|\n\s*\n\s*nanoGentzen|$))', answer, re.DOTALL | re.IGNORECASE)
            if sub_ans and len(sub_ans.group(1).strip().split()) >= 3:
                answer = sub_ans.group(1).strip()
            else:
                clean_ans = re.split(r'(?:\d+\.\s*\*\*Review|\*\*Review\s+against|\*+Review\b)', answer, flags=re.IGNORECASE)[0].strip()
                if len(clean_ans.split()) >= 3:
                    answer = clean_ans
                else:
                    paras = [p.strip() for p in answer.split("\n\n") if p.strip() and not p.strip().startswith(("*", "1.", "2.", "3.", "4.", "5.", "6.", "7.", "8.", "9.", "Drafting", "Critique"))]
                    if paras:
                        answer = paras[-1]
                    elif fallback_answer:
                        answer = fallback_answer

        if answer and "<answer>" in answer:
            answer = answer.split("<answer>")[-1].strip()
        if answer:
            answer = re.sub(r'</?answer>', '', answer, flags=re.IGNORECASE).strip()

        if not answer:
            answer = fallback_answer or "Verified."
        if answer:
            answer = _clean_discourse_sentence(answer)

        # Guard against truncated answers ending mid-sentence
        if answer and not answer.rstrip().endswith(('.', '!', '?', '"', "'", "’", "”")):
            ans_sentences = [s.strip() for s in re.split(r'(?<=[.!?])\s+', answer) if s.strip()]
            if len(ans_sentences) > 1:
                answer = " ".join(ans_sentences[:-1])
            elif fallback_answer:
                clean_fb = _clean_discourse_sentence(fallback_answer)
                answer = answer.strip() + (f", concluding that {clean_fb[:1].lower() + clean_fb[1:]}" if clean_fb else "")

        if reasoning:
            reasoning = re.sub(r'^</?(?:reasoning|think|thought)>', '', reasoning, flags=re.IGNORECASE).strip()
            reasoning = self._sanitize_regular_text(reasoning)
            reasoning = make_reasoning_direct(reasoning)
            answer = self._sanitize_regular_text(answer)
            reasoning = self._strip_tautological_lead(reasoning, answer)
            reasoning = re.sub(r'\.{2,}', '.', reasoning)
            answer = re.sub(r'\.{2,}', '.', answer)
            return {
                "question": question,
                "reasoning": reasoning,
                "answer": answer,
            }

        return None

    def _strip_tautological_lead(self, reasoning: str, answer: str) -> str:
        """Strip redundant opening sentence that simply echoes the final answer verbatim."""
        sents = re.split(r'(?<=[.!?])\s+', reasoning.strip())
        if len(sents) < 2:
            return reasoning
        s0 = sents[0].strip().rstrip('.!?')
        a_clean = answer.strip().rstrip('.!?')

        s0_words = set(re.findall(r'\b[a-zA-Z]{3,}\b', s0.lower()))
        a_words = set(re.findall(r'\b[a-zA-Z]{3,}\b', a_clean.lower()))
        overlap = len(s0_words & a_words) / max(1, len(s0_words | a_words))

        if overlap > 0.70:
            remaining = sents[1:]
            lead2 = remaining[0]
            lead2 = re.sub(r'^(?:This\s+conclusion\s+follows\s+from[^:]*:\s*|This\s+is\s+because\s+|Specifically,?\s*)', '', lead2, flags=re.IGNORECASE)
            lead2 = lead2.strip()
            if lead2 and lead2[0].islower():
                lead2 = lead2[0].upper() + lead2[1:]
            remaining[0] = lead2
            return ' '.join(remaining)
        return reasoning

    def _sanitize_regular_text(self, text: str) -> str:
        """Strip turnstiles, logic notation, and formal proof terminology from verbal text."""
        t = text
        # 1. Strip turnstiles and formal notation
        t = re.sub(r'\\[a-zA-Z]+', '', t)
        t = re.sub(r'[⊢⊣⊨→⇒↔⇔∧∨¬~∀∃λ]', ' ', t)
        t = re.sub(r'[\$\{\}\[\]]', '', t)
        t = re.sub(r'_+', ' ', t)

        # 2. Strip formal logic jargon and pipeline meta-language
        t = re.sub(r'\b(?:since|as)\s+the\s+nanoGentzen\s+(?:sequence|logic\s+tree|framework|derivation)\s+(?:confirms|establishes|shows|validates|indicates)\s+that\b', 'since', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:the\s+)?nanoGentzen\s+(?:sequence|logic\s+tree|framework|derivation)\s+(?:establishes|confirms|validates|supports\s+this\s+by\s+establishing|supports|shows|indicates|posits)\s+that\b', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:the\s+)?nanoGentzen\s+(?:sequence|logic\s+tree|framework|derivation)\s*:\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:the\s+)?nanoGentzen\s+(?:sequence|logic\s+tree|framework|derivation)\s+', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:within|along)\s+the\s+nanoGentzen(?:\s+Deductive)?\s+Logic\s+Tree\b', 'through deductive analysis', t, flags=re.IGNORECASE)
        t = re.sub(r'\bnanoGentzen(?:\s+Deductive)?\s+Logic\s+Tree\b', 'deductive analysis', t, flags=re.IGNORECASE)
        t = re.sub(r'\bnanoGentzen\b', 'deductive analysis', t, flags=re.IGNORECASE)
        t = re.sub(r'\bthe\s+sequent\s+(?:demonstrates|shows|establishes|indicates|proves)\s+that\b', 'deductive analysis indicates that', t, flags=re.IGNORECASE)
        t = re.sub(r'\bthe\s+sequent\b', 'the formal structure', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:by|applying)\s+Modus\s+Ponens(?:\s+to\s+[^,.:;]+)?\b', 'by step-by-step reasoning', t, flags=re.IGNORECASE)
        t = re.sub(r'\bModus\s+Ponens\b', 'deductive reasoning', t, flags=re.IGNORECASE)
        t = re.sub(r'\bfrom\s+Axiom\s+\d+\s*:*\b', 'from foundational principles:', t, flags=re.IGNORECASE)
        t = re.sub(r'\b([A-Z][a-z]+)\s+\1\b', r'\1', t)   # doubled proper name ("Searle Searle")

        # Clean citation format "et al." to author name (e.g. "Doerig et al." -> "Doerig")
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\.?[’\']s\b', r"\1's", t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\.\s*', r'\1 ', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+et\s+al\b', r'\1', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+[Aa]rgue\b', r'\1 argues', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+[Aa]ssert\b', r'\1 asserts', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+[Pp]osit\b', r'\1 posits', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+[Rr]equire\b', r'\1 requires', t)
        t = re.sub(r'\b([A-Z][a-zA-Z\-]+)\s+[Ii]nterpret\b', r'\1 interprets', t)

        # 3. PURGE "WHAT TEXT!?" META-PHRASES
        # "The text explicitly categorizes X as..." -> "X is categorized as..."
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\s+(?:explicitly\s+)?categorizes\s+([a-zA-Z0-9_\-\s]+?)\s+as\b',
            r'\1 is categorized as',
            t,
            flags=re.IGNORECASE
        )
        # "The text's acknowledgment / discussion of X..." -> "Recognizing X..."
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)[’\']s\s+(?:acknowledgment|discussion|analysis|framing|treatment)\s+of\b',
            'recognizing',
            t,
            flags=re.IGNORECASE
        )
        # "The text establishes / states / notes that..." -> ""
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)(?:[’\']s)?\s+(?:explicitly\s+)?(?:states|defines|explains|notes|highlights|argues|suggests|posits|indicates|establishes|shows|asserts|claims|proposes)\s+that\b',
            '',
            t,
            flags=re.IGNORECASE
        )
        # "The text highlights epistemic gaps" -> "Epistemic gaps"
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\s+(?:explicitly\s+)?(?:highlights|presents|examines|identifies|outlines)\s+',
            '',
            t,
            flags=re.IGNORECASE
        )
        # "The text acknowledges..." -> "It is recognized that..."
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\s+acknowledges\b',
            'it is recognized that',
            t,
            flags=re.IGNORECASE
        )
        # "The text further defines..."
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\s+further\s+defines\b',
            'analysis further defines',
            t,
            flags=re.IGNORECASE
        )
        # "within / in / from / across the text"
        t = re.sub(
            r'\b(?:within|in|from|across|throughout)\s+(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\b',
            '',
            t,
            flags=re.IGNORECASE
        )
        # "According to the text / document / author"
        t = re.sub(
            r'\baccording\s+to\s+(?:the|this)\s+(?:text|document|article|excerpt|passage|paper|author)\b,?\s*',
            '',
            t,
            flags=re.IGNORECASE
        )
        # "as stated in the text"
        t = re.sub(
            r'\bas\s+(?:stated|noted|described|explained)\s+in\s+(?:the|this)\s+(?:text|document|article|excerpt|passage|paper)\b,?\s*',
            '',
            t,
            flags=re.IGNORECASE
        )
        # Fallback: any remaining isolated "the text" or "this text"
        t = re.sub(
            r'\b(?:the|this)\s+(?:text|document|passage|excerpt)\b',
            'the theoretical framework',
            t,
            flags=re.IGNORECASE
        )

        # Stray XML/HTML tags
        t = re.sub(r'</?(?:reasoning|think|thought|answer)>', '', t, flags=re.IGNORECASE)

        # Scaffolding headers purge
        t = re.sub(r'\b(?:the\s+theoretical\s+framework\s+establishes\s+(?:three|two|four|\d+)?\s*(?:foundational\s+premises|premises)?)\s*:?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:establishes\s+(?:three|two|four|\d+)?\s*(?:foundational\s+premises|premises))\s*:?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:establish\s+foundational\s+premises|foundational\s+premises)\s*:\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:trace\s+the\s+inferential\s+bridge|inferential\s+bridge)\s*:\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:apply\s+domain\s+constraints|address\s+domain\s+constraints|domain\s+constraints)\s*:\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:synthesize\s+the\s+conclusion|synthesize\s+conclusion)\s*:\s*', '', t, flags=re.IGNORECASE)

        # Leading conversational preambles: "The question asks for X..." / "The question addresses X..."
        # Robust sentence boundary matching protecting acronyms like U.S., e.g., i.e.
        t = re.sub(
            r'^(?:The\s+question\s+(?:asks|addresses|explores|examines|focuses|investigates|inquires).*?(?<!\b[A-Za-z]\.)(?<!\b[A-Za-z])[.!?](?=\s+[A-Z]|\s*$)\s*)',
            '',
            t,
            flags=re.IGNORECASE
        )
        # Orphaned initial fragments from previous broken trimming (e.g. "S. Constitution and contemporary...")
        t = re.sub(
            r'^(?:[A-Z]\.\s+.*?(?<!\b[A-Za-z]\.)(?<!\b[A-Za-z])[.!?](?=\s+[A-Z]|\s*$)\s*)',
            '',
            t,
            flags=re.IGNORECASE
        )
        t = re.sub(r'^(?:To\s+(?:address|resolve|answer)\s+(?:the|this)\s+question,?\s*)', '', t, flags=re.IGNORECASE)
        t = re.sub(r'^(?:In\s+order\s+to\s+answer\s+(?:the|this)\s+question,?\s*)', '', t, flags=re.IGNORECASE)

        # Meta-scaffolding clauses:
        t = re.sub(
            r'^(?:To\s+(?:resolve|address|answer)\s+this,?\s*we\s+must\s+(?:first\s+)?establish.*?(?<!\b[A-Za-z]\.)(?<!\b[A-Za-z])[.!?]\s*)',
            '',
            t,
            flags=re.IGNORECASE
        )
        t = re.sub(
            r'\bThe\s+(?:logical|inferential)\s+bridge\s+connects\s+.*?(?<!\b[A-Za-z]\.)(?<!\b[A-Za-z])[.!?]\s*',
            '',
            t,
            flags=re.IGNORECASE
        )

        # Meta conclusion endings
        t = re.sub(r'\b(?:this\s+(?:conclusion|synthesis)?\s*directly\s+(?:addresses|answers)\s+the\s+question\s+by\s+[^.!?]+[.!?])\s*', '', t, flags=re.IGNORECASE)

        # Book, chapter, page, author mentions and prepositional references
        t = re.sub(r'\b(?:in|from|of|throughout|across|by|under)\s+(?:chapter\s+\d+(?:\s+of\s+the\s+book)?|section\s+\d+|the\s+book)\b,?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:chapter\s+\d+(?:\s+of\s+the\s+book)?|section\s+\d+|in\s+the\s+book|the\s+book)\b,?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\b(?:from\s+the\s+foundational\s+premise\s+in\s+)?(?:page\s+\d+|p\.\s*\d+),?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r',?\s*\bas\s+the\s+author\s+argues\b', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\bthe\s+author\s+(?:argues|states|notes|explains)\s+(?:that\s+)?', '', t, flags=re.IGNORECASE)

        # "in the source material / source text / provided material"
        t = re.sub(r'\bin\s+(?:the\s+)?source\s+(?:material|text|documents?|passages?)\b,?\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r'\blocat(?:e|ing)\s+the\s+explicit\s+statement(?:\s+confirming[^:]*:*|\s*:*)', 'specifically,', t, flags=re.IGNORECASE)

        # Dangling prepositions before punctuation marks: e.g. "outlined in ." -> "outlined."
        t = re.sub(r'\b(?:in|at|on|from|of|by|to|for|with|as|under)\s+([.,;:?!])', r'\1', t, flags=re.IGNORECASE)

        # Footnote reference numbers attached or spaced after punctuation
        t = re.sub(r'([.?!,”"\'\)])\s*\d{1,3}(?!\.)\s+(?=[A-Z“"\'\(])', r'\1 ', t)
        t = re.sub(r'([”"\'\)])\s*\d{1,3}(?=[.,;:?!])', r'\1', t)
        t = re.sub(r'([.?!,”"\'\)])\s*\d{1,3}\.?\s*$', r'\1', t)

        # 4. Clean punctuation, inline numbering markers, and whitespace
        t = re.sub(r'\([0-9ivx]+\)\s*', '', t, flags=re.IGNORECASE)
        t = re.sub(r':{2,}', ':', t)
        t = re.sub(r'\s*,\s*,', ',', t)
        t = re.sub(r'\s*\.\s*\.', '.', t)
        t = re.sub(r'\s+([.,;:?!])', r'\1', t)
        t = re.sub(r'[ \t]+', ' ', t)

        # Capitalize sentences and purge robotic ordinals/checklists ("First, ... Second, ...", "1. ...", "(1) ...")
        # Mask common academic/latin abbreviations so sentence splitter does not break mid-sentence
        t, _abbr_orig = mask_abbreviations(t)

        sentences = re.split(r'(?<=[.!?])\s+', t)
        cleaned_sents = []
        for s in sentences:
            s_clean = s.strip()
            # Restore abbreviations
            s_clean = unmask_abbreviations(s_clean, _abbr_orig)
            # Strip leading robotic ordinals
            s_clean = re.sub(
                r'^(?:first|second|third|fourth|fifth|sixth|seventh|eighth|finally|lastly),?\s*',
                '',
                s_clean,
                flags=re.IGNORECASE
            )
            # Strip leading list markers like "(1)", "1.", "1)", "(i)"
            s_clean = re.sub(r'^\(?[0-9ivx]+\)[\.\:\s]*', '', s_clean, flags=re.IGNORECASE)
            s_clean = re.sub(r'^[0-9ivx]+\.[\:\s]*', '', s_clean, flags=re.IGNORECASE)

            # Repair headless active verbs created by stripped subject clauses
            s_clean = re.sub(r'^(?:applies\s+this\s+to\b)', 'This applies to', s_clean, flags=re.IGNORECASE)
            s_clean = re.sub(r'^(?:applies\s+to\b)', 'This applies to', s_clean, flags=re.IGNORECASE)
            s_clean = re.sub(r'^(?:demonstrates|shows|establishes|indicates|examines|identifies|outlines|discusses|posits)\s+that\b', 'Analysis demonstrates that', s_clean, flags=re.IGNORECASE)

            # Clean trailing dangling prepositions before sentence end
            s_clean = re.sub(r'\b(?:in|at|on|from|of|by|to|for|with|as|under)\s*$', '', s_clean, flags=re.IGNORECASE).strip()
            s_clean = re.sub(r'\s+([.,;:?!])', r'\1', s_clean)

            if s_clean and s_clean[0].islower():
                s_clean = s_clean[0].upper() + s_clean[1:]
            if s_clean:
                cleaned_sents.append(s_clean)
        return " ".join(cleaned_sents).strip()

    def _compute_clarity_score(self, reasoning: str) -> float:
        words = len(reasoning.split())
        if words == 0:
            return 0.0

        len_score = 1.0 if (40 <= words <= 250) else max(0.5, 1.0 - abs(words - 130) / 200.0)
        connectives = ["therefore", "because", "implies", "since", "consequently", "given", "yields", "thus", "established", "deduces"]
        connective_count = sum(1 for w in connectives if w in reasoning.lower())
        conn_score = min(1.0, connective_count / 3.0)

        return round(0.6 * len_score + 0.4 * conn_score, 2)

    def _heuristic_fallback(
        self,
        question: str,
        target_claim: str,
        logic_tree: str,
        context_text: str = "",
        error: Optional[str] = None,
        path_nodes: Optional[List[str]] = None,
        key_premises: Optional[List[str]] = None,
        is_verified: bool = True,
        epistemic_status: str = "PROVEN_TRUE",
        relevance_info: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """
        Constructs a natural, authentic ClearCoT analytical deduction adhering
        to the ClearCoT methodology without robotic templates or conversational filler.
        """
        target_clean = _clean_discourse_sentence(target_claim).rstrip(".")
        clean_sentences = [
            _clean_discourse_sentence(s) for s in re.split(r'(?<=[.!?])\s+', context_text)
            if len(_clean_discourse_sentence(s)) > 30 and not any(bad in s.lower() for bad in ("table ", "figure ", "creativecommons", "license", "doi.org"))
        ]

        ev1 = clean_sentences[0].rstrip(".") if clean_sentences else ""
        ev2 = clean_sentences[1].rstrip(".") if len(clean_sentences) > 1 else ""
        ev3 = clean_sentences[2].rstrip(".") if len(clean_sentences) > 2 else ""

        # Build direct, load-bearing ClearCoT internal monologue
        reasoning_parts = []
        if ev1:
            reasoning_parts.append(f"{ev1}.")
        if ev2:
            reasoning_parts.append(f"Examining the underlying mechanism, {_lower_first_if_not_proper(ev2)}.")
        if ev3:
            reasoning_parts.append(f"This directly interacts with the requirement that {_lower_first_if_not_proper(ev3)}.")

        if target_clean and (not ev1 or target_clean.lower() != ev1.lower()):
            reasoning_parts.append(f"Consequently, {_lower_first_if_not_proper(target_clean)}.")
        else:
            reasoning_parts.append("Tracing these deductive principles directly resolves the inquiry.")

        reasoning = " ".join(reasoning_parts)
        reasoning = self._sanitize_regular_text(reasoning)
        reasoning = make_reasoning_direct(reasoning)
        reasoning = re.sub(r'\.{2,}', '.', reasoning)

        # Build authoritative final answer
        if ev2 and target_clean and target_clean.lower() not in ev2.lower():
            answer = f"{target_clean}. Specifically, {_lower_first_if_not_proper(ev2)}."
        elif target_clean:
            answer = f"{target_clean}."
        else:
            answer = "These foundational principles directly confirm this relationship."
        answer = self._sanitize_regular_text(answer)
        answer = re.sub(r'\.{2,}', '.', answer)

        grounding = self.verify_cot_grounding(
            reasoning=reasoning,
            answer=answer,
            logic_tree_res={
                "is_verified": is_verified,
                "logic_tree_text": logic_tree,
                "relevance": relevance_info,
                "epistemic_status": epistemic_status,
            },
            path_nodes=path_nodes,
            key_premises=key_premises,
            target_claim=target_clean,
        )

        fallback_result = {
            "question": question,
            "reasoning": reasoning,
            "answer": answer,
            "reasoning_tokens_estimate": int(len(reasoning.split()) * 1.3),
            "clarity_score": self._compute_clarity_score(reasoning),
            "is_fallback": True,
            "grounding": grounding,
            "grounding_score": grounding["grounding_score"],
            "is_grounded": grounding["is_grounded"],
        }
        if error:
            fallback_result["error"] = error
        return fallback_result

    def verify_cot_grounding(
        self,
        reasoning: str,
        answer: str,
        logic_tree_res: Optional[Dict[str, Any]] = None,
        path_nodes: Optional[List[str]] = None,
        key_premises: Optional[List[str]] = None,
        target_claim: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Verifies that the natural language ClearCoT reasoning trace and answer
        are strictly grounded in the formal nanoGentzen logic tree and verified sequent.

        Evaluates 4 core dimensions:
        1. Node / Concept Coverage (40%): Presence of intermediate deductive steps and atoms.
        2. Conclusion Alignment (30%): Semantic derivation of the target proposition.
        3. Relevance Distractor Isolation (20%): Successful omission of non-causal premises.
        4. Epistemic Consistency (10%): Match between modal tone and Saul Kripke provability status.
        """
        tree_res = logic_tree_res or {}
        all_nodes: List[str] = []

        # 1. Harvest target concepts
        if path_nodes:
            for p in path_nodes:
                clean_p = re.sub(r'[_]+', ' ', str(p)).strip()
                if clean_p and clean_p not in all_nodes:
                    all_nodes.append(clean_p)

        if key_premises:
            for kp in key_premises:
                clean_kp = re.sub(r'[_]+', ' ', str(kp)).strip()
                if clean_kp and len(clean_kp) < 70 and clean_kp not in all_nodes:
                    all_nodes.append(clean_kp)

        # From logic tree text or derivation steps
        tree_text = tree_res.get("logic_tree_text", "")
        if tree_text:
            for line in tree_text.splitlines():
                if "Established:" in line:
                    atom = line.split("Established:")[-1].strip(" `")
                    atom = re.sub(r'\[.*?\]', '', atom)
                    atom = re.sub(r'[_]+', ' ', atom).strip()
                    if atom and len(atom) < 70 and atom not in all_nodes:
                        all_nodes.append(atom)

        for step in tree_res.get("derivation_steps", []):
            c = step.get("conclusion", "")
            if c:
                clean_c = re.sub(r'[_]+', ' ', re.sub(r'\[.*?\]', '', c)).strip()
                clean_c = re.sub(r'^[A-Z0-9_]+\s*:\s*', '', clean_c).strip()
                if clean_c and len(clean_c) < 70 and clean_c not in all_nodes:
                    all_nodes.append(clean_c)

        if not all_nodes and target_claim:
            all_nodes.append(target_claim)

        combined_text = f"{reasoning} {answer}"
        covered = [n for n in all_nodes if _matches_concept(n, combined_text)]
        missing = [n for n in all_nodes if n not in covered]
        node_coverage = round(len(covered) / max(1, len(all_nodes)), 2)

        # 2. Conclusion Alignment
        goal = target_claim or ""
        if not goal and tree_res.get("sequent"):
            parts = re.split(r'\\?vdash|⊢', tree_res["sequent"])
            if len(parts) > 1:
                goal = parts[-1].strip()

        stopwords = {"the", "and", "for", "with", "that", "this", "from", "are", "is", "was", "were", "been", "have", "has", "had", "to", "in", "on", "at", "by", "an", "a", "of"}
        claim_words = [re.sub(r'[^a-z0-9]', '', w) for w in goal.lower().split()]
        claim_words = [w for w in claim_words if len(w) > 2 and w not in stopwords]
        if claim_words:
            ans_words = set(re.findall(r'\b[a-z0-9]+\b', answer.lower()))
            ans_stems = {_stem_word(w) for w in ans_words}
            ans_match = sum(1 for w in claim_words if w in ans_words or _stem_word(w) in ans_stems) / len(claim_words)

            r_sents = [s for s in re.split(r'(?<=[.!?])\s+', reasoning) if s.strip()]
            r_end = " ".join(r_sents[-2:]) if r_sents else reasoning
            r_words = set(re.findall(r'\b[a-z0-9]+\b', r_end.lower()))
            r_stems = {_stem_word(w) for w in r_words}
            r_match = sum(1 for w in claim_words if w in r_words or _stem_word(w) in r_stems) / len(claim_words)
            conclusion_alignment = round(max(ans_match, r_match * 0.9), 2)
        else:
            conclusion_alignment = 1.0

        # 3. Relevance Distractor Isolation
        relevance_info = tree_res.get("relevance", {})
        unused = relevance_info.get("unused_premises", []) if relevance_info else []
        leaked = []
        for u in unused:
            clean_u = re.sub(r'[_]+', ' ', u).strip()
            if _matches_concept(clean_u, reasoning):
                leaked.append(clean_u)
        relevance_isolation = round(max(0.0, 1.0 - (len(leaked) / max(1, len(unused)))), 2) if unused else 1.0

        # 4. Epistemic Consistency
        epistemic_status = tree_res.get("epistemic_status", "PROVEN_TRUE")
        r_lower = reasoning.lower()
        deductive_markers = ["therefore", "thus", "consequently", "establishes", "leads to", "yields", "proves", "demonstrates", "necessarily", "synthesizing"]
        undecided_markers = ["open", "epistemic gap", "ambiguity", "unclear", "insufficient", "undecided", "cannot determine", "hypothetical", "depends on"]
        if epistemic_status == "PROVEN_TRUE":
            epistemic_consistency = 1.0 if any(m in r_lower for m in deductive_markers) else 0.8
        elif epistemic_status == "INTUITIONISTIC_UNDECIDED":
            epistemic_consistency = 1.0 if any(m in r_lower for m in undecided_markers) else 0.7
        elif epistemic_status == "PROVEN_FALSE":
            epistemic_consistency = 1.0 if any(m in r_lower for m in ["contradiction", "counterexample", "false", "fails", "incompatible"]) else 0.6
        else:
            epistemic_consistency = 1.0

        # Composite Grounding Score
        grounding_score = round(
            0.40 * node_coverage +
            0.30 * conclusion_alignment +
            0.20 * relevance_isolation +
            0.10 * epistemic_consistency,
            2
        )

        is_tree_verified = tree_res.get("is_verified", True)
        is_grounded = bool(is_tree_verified and grounding_score >= 0.70 and node_coverage >= 0.50)

        return {
            "is_grounded": is_grounded,
            "grounding_score": grounding_score,
            "node_coverage": node_coverage,
            "covered_nodes": covered,
            "missing_nodes": missing,
            "conclusion_alignment": conclusion_alignment,
            "relevance_isolation": relevance_isolation,
            "epistemic_consistency": epistemic_consistency,
            "leaked_distractors": leaked,
        }

    def generate_naive_cot(
        self,
        question: str,
        target_claim: str,
        context_text: str = "",
        model: str = "qwen2.5:7b",
        return_meta: bool = False,
    ):
        """
        Generates an authentic verbose, rambling baseline Chain-of-Thought
        for contrastive DPO preference training (Occam-2B specification).
        Contains conversational canopy, backtracking, and informal reasoning flaws.
        With return_meta=True returns {"text": ..., "synthetic": bool}; synthetic = the fixed template
        was used because the LLM was unavailable or returned too little (a weak DPO negative).
        """
        def _out(text: str, synthetic: bool):
            return {"text": text, "synthetic": synthetic} if return_meta else text

        if not self.llm_client or not self.llm_client.health_check():
            return _out(self._construct_synthetic_naive_cot(question, target_claim, context_text), True)

        prompt = (
            f"### Context:\n{context_text[:2000]}\n\n"
            f"### Question:\n{question}\n\n"
            f"### Expected Answer Concept:\n{target_claim}\n\n"
            "Following the ClearCoT methodology (Appendix A.1/A.3), write an unoptimized, naive internal thinking trace (<think>) attempting to answer this question.\n"
            "REQUIREMENTS:\n"
            "1. Produce a rambling, unoptimized reasoning trace that displays typical informal reasoning flaws: conversational canopy, hesitation, redundant deliberation, and a circular or unsupported inferential leap before arriving at the conclusion.\n"
            "2. Ground the thoughts plausibly in the provided concepts.\n"
            "3. STRICT NEGATIVE CONSTRAINTS:\n"
            "   - NEVER recite, quote, or echo these prompt instructions.\n"
            "   - NEVER use meta-phrases like 'The question asks for a verbose...', 'The answer should be rambling...', or 'internal monologue'.\n"
            "   - Output ONLY the thinking trace between <think> and </think>:"
        )
        for attempt in range(2):   # a trace that echoes the instructions is retried once, then replaced
            try:
                raw = self.llm_client.generate(
                    prompt=prompt,
                    model=model,
                    temperature=0.6 + 0.2 * attempt,
                    max_tokens=400,
                )
                r_match = re.search(r'<(?:think(?:ing)?|reasoning|thought(?:s|_process)?|ThinkingTraces?)>(.*?)</(?:think(?:ing)?|reasoning|thought(?:s|_process)?|ThinkingTraces?)>', raw, re.DOTALL | re.IGNORECASE)
                extracted = r_match.group(1).strip() if r_match else raw
                cleaned = re.sub(r'</?(?:reasoning|think(?:ing)?|thought(?:s|_process)?|ThinkingTraces?|answer)>', '', extracted, flags=re.IGNORECASE).strip()

                # Purge any accidental prompt leakage
                cleaned = re.sub(
                    r'^(?:##\s*Reasoning\s*)?Okay,\s*let\s*me\s*(?:carefully\s*)?(?:examine|think|look|unpack)[^.]*?(?:asking\s+for|should\s+be|typical)\s+(?:a\s+)?(?:verbose|rambling|internal\s+monologue|conversational\s+markers)[^.]*\.\s*',
                    '',
                    cleaned,
                    flags=re.IGNORECASE
                )
                cleaned = re.sub(
                    r'\b(?:the\s+question\s+(?:is\s+)?asking\s+for|the\s+answer\s+should\s+be)\s+(?:a\s+)?(?:verbose|rambling|internal\s+monologue)[^.]*\.\s*',
                    '',
                    cleaned,
                    flags=re.IGNORECASE
                )
                leak = naive_trace_leak(cleaned)
                if leak:
                    logger.info(f"Naive CoT echoes its instructions ({leak!r}); attempt {attempt + 1}/2")
                    continue
                if len(cleaned.split()) > 35:
                    return _out(cleaned.strip(), False)
            except Exception as e:
                logger.warning(f"Naive CoT generation failed: {e}")
                break

        return _out(self._construct_synthetic_naive_cot(question, target_claim, context_text), True)

    def generate_standard_cot(
        self,
        question: str,
        context_text: str = "",
        model: str = "qwen2.5:7b",
        max_tokens: int = 768,
    ) -> Optional[str]:
        """
        Baseline for measuring token savings: the same model answering with an ordinary step-by-step
        prompt (no ClearCoT guide, not told to ramble). None when the LLM is unavailable; there is no
        template fallback, because a made-up baseline would make the measurement meaningless.
        """
        if not self.llm_client or not self.llm_client.health_check():
            return None
        prompt = (f"### Context:\n{context_text[:2000]}\n\n### Question:\n{question}\n\n"
                  "Think step by step inside <think></think>, then give the answer inside <answer></answer>.")
        try:
            raw = self.llm_client.generate(prompt=prompt, model=model, temperature=0.3, max_tokens=max_tokens)
        except Exception as e:
            logger.warning(f"Standard CoT baseline failed: {e}")
            return None
        m = re.search(r"<think>(.*?)</think>", raw or "", re.DOTALL | re.IGNORECASE)
        text = (m.group(1) if m else re.split(r"<answer>", raw or "", flags=re.IGNORECASE)[0]).strip()
        text = re.sub(r"</?(?:think|reasoning|answer)>", "", text).strip()
        return text if len(text.split()) >= 10 else None

    @staticmethod
    def measure_token_savings(clearcot_reasoning: str, baseline_reasoning: Optional[str]) -> Optional[int]:
        """
        Percent fewer reasoning tokens than the baseline, rounded; negative when ClearCoT is longer.
        None when there is no real baseline. (Same 1.3 tokens/word estimate for both sides.)
        """
        if not baseline_reasoning or not clearcot_reasoning:
            return None
        b = len(baseline_reasoning.split()) * 1.3
        r = len(clearcot_reasoning.split()) * 1.3
        return int(round((b - r) / b * 100)) if b > 0 else None

    def _construct_synthetic_naive_cot(
        self,
        question: str,
        target_claim: str,
        context_text: str = ""
    ) -> str:
        """
        Synthesizes an authentic meandering, conversational reasoning trace
        matching the ClearCoT paper (Occam-2B Appendix A.1 / A.3) verbose baseline.
        """
        sentences = [
            _clean_discourse_sentence(s) for s in re.split(r'(?<=[.!?])\s+', context_text)
            if len(_clean_discourse_sentence(s)) > 25 and not any(bad in s.lower() for bad in ("table", "figure", "doi.org"))
        ]
        s1 = sentences[0] if sentences else "there are multiple interrelated principles"
        s2 = sentences[1] if len(sentences) > 1 else "the mechanisms need to be evaluated"
        s3 = sentences[2] if len(sentences) > 2 else "certain definitions remain complex"

        q_topic = question.rstrip("?").strip()
        if q_topic.lower().startswith(("how ", "why ", "what ", "in ")):
            q_topic = re.sub(r'^(?:how\s+does|how\s+do|why\s+does|what\s+is|what\s+are|in\s+what\s+way\s+does)\s+', '', q_topic, flags=re.IGNORECASE)

        naive_trace = (
            f"Okay, let me think through this question carefully. We need to analyze {q_topic.strip()}. "
            f"Looking at the background concepts, {_lower_first_if_not_proper(s1.rstrip('.'))}. "
            f"Wait, does that directly resolve the whole issue? Not necessarily, because there is another angle to consider. "
            f"Specifically, {_lower_first_if_not_proper(s2.rstrip('.'))}. "
            f"So if we put those two things together, what does that imply? "
            f"Well, there's also the point that {_lower_first_if_not_proper(s3.rstrip('.'))}. "
            f"I was wondering if maybe this means something else, but looking closely at the concepts, "
            f"it really seems that {_lower_first_if_not_proper(target_claim.rstrip('.'))}. "
            f"Yes, that should be the main takeaway."
        )
        return naive_trace
